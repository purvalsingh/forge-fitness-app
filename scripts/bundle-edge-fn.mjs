/**
 * Inline the shared prompts module into the Edge Function source.
 * The Management API deploy takes a single file, while the CLI would bundle imports for us.
 */
import fs from 'node:fs'

const shared = fs.readFileSync('supabase/functions/_shared/prompts.ts', 'utf8')
  .replace(/^\/\/ deno-lint-ignore-file.*$/m, '')
  .replace(/^export /gm, '')

const fn = fs.readFileSync('supabase/functions/ai/index.ts', 'utf8')
  .replace(/^import \{[^}]*\} from '\.\.\/_shared\/prompts\.ts'\n/m, '')

process.stdout.write(`// Generated by scripts/bundle-edge-fn.mjs — edit the sources, not this file.\n${shared}\n${fn}`)
